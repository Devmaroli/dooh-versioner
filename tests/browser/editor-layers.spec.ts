import { expect, test } from '@playwright/test'
import fs from 'node:fs'

test('actual source rows, background, border and anchored stamp/logo link are usable in edit', async ({ page }) => {
  const fixture = process.env.IKEA_PSD
  test.skip(!fixture || !fs.existsSync(fixture), 'Set IKEA_PSD to the private local fixture.')
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/'); await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(fixture!)
  await page.getByLabel('Language for ikea.psd').selectOption('EN')
  await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  const source = page.locator('.analyse-layer')
  await source.nth(4).click(); await page.getByRole('button', { name: 'Campaign stamp / label', exact: true }).click()
  await source.nth(8).click(); await page.getByRole('button', { name: 'Brand logo', exact: true }).click()
  await source.nth(6).click(); await page.getByRole('button', { name: 'Main headline', exact: true }).click()
  await page.getByRole('button', { name: 'Trace original border', exact: true }).click()
  for (const [label, value] of [['X', '99'], ['Y', '279'], ['Width', '1522'], ['Height', '732']]) await page.getByRole('spinbutton', { name: label, exact: true }).fill(value)
  await page.getByRole('button', { name: 'Use original border', exact: true }).click()
  await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  await page.screenshot({ path: 'work/editor-layer-audit.png' })
  const rows = page.locator('.editor-layer-row'), stamp = rows.filter({ hasText: /stamp ·/ }), logo = rows.filter({ has: page.getByRole('button', { name: 'Select layer CTA', exact: true }) })
  expect(await rows.count()).toBeGreaterThan(8)
  await stamp.getByRole('button', { name: /^Select layer / }).click()
  const stampBox = (await page.locator('.guide-object.selected').boundingBox())!
  const spot = await stamp.locator('canvas').evaluate((c: HTMLCanvasElement, aspect: number) => {
    const d = c.getContext('2d')!.getImageData(0, 0, c.width, c.height).data, w = Math.min(c.width, c.height * aspect), h = w / aspect, ox = (c.width - w) / 2, oy = (c.height - h) / 2
    for (let y = Math.ceil(oy); y < oy + h; y++) for (let x = Math.ceil(ox); x < ox + w; x++) if (d[(y * c.width + x) * 4 + 3] > 180) return { x: (x + .5 - ox) / w, y: (y + .5 - oy) / h }
    throw new Error('No visible stamp pixel')
  }, stampBox.width / stampBox.height)
  await logo.getByRole('button', { name: /^Select layer / }).click()
  await page.mouse.click(stampBox.x + spot.x * stampBox.width, stampBox.y + spot.y * stampBox.height)
  await expect(stamp).toHaveClass(/selected/)
  const stampX = await page.getByLabel('X position (%)', { exact: true }).inputValue()
  await logo.getByRole('button', { name: /^Select layer / }).click(); await page.getByLabel('X position (%)', { exact: true }).fill('50')
  await stamp.getByRole('button', { name: /^Select layer / }).click()
  await expect(page.getByLabel('X position (%)', { exact: true })).toHaveValue(stampX)
  await logo.locator('input').check()
  const link = page.getByRole('button', { name: 'Link selected layers', exact: true })
  await expect(link).toBeEnabled(); await link.click()
  await expect(page.getByRole('button', { name: 'Unlink selected layers', exact: true })).toBeEnabled()
  await expect(rows.filter({ hasText: 'Linked ·' })).toHaveCount(2)
  await page.getByLabel('Width (%)', { exact: true }).fill('60')
  await page.screenshot({ path: 'work/editor-linked-layers.png' })
  await page.getByRole('button', { name: 'Unlink selected layers', exact: true }).click()
  await expect(rows.filter({ hasText: 'Linked ·' })).toHaveCount(0)
  await page.getByRole('button', { name: /^bg\b.*Background/ }).click()
  await expect(page.getByRole('heading', { name: 'Original background', exact: true })).toBeVisible()
  await expect(page.getByLabel('X position (%)', { exact: true })).toHaveCount(0)
  const beforeBackground = await page.locator('.calibration-canvas-frame .proof-canvas canvas').evaluate((c: HTMLCanvasElement) => c.toDataURL())
  await page.getByRole('button', { name: 'Scale S', exact: true }).click()
  const bgHandle = page.getByRole('button', { name: 'Scale from bottom right', exact: true }), handleBox = (await bgHandle.boundingBox())!
  await page.mouse.move(handleBox.x + 7, handleBox.y + 7); await page.mouse.down(); await page.mouse.move(handleBox.x + 27, handleBox.y + 27, { steps: 4 }); await page.mouse.up()
  await expect.poll(async()=>Number(await page.getByLabel('Background scale (%)', { exact: true }).inputValue())).toBeGreaterThan(100)
  await page.getByLabel('Background scale (%)', { exact: true }).fill('200')
  const afterBackground = await page.locator('.calibration-canvas-frame .proof-canvas canvas').evaluate((c: HTMLCanvasElement) => c.toDataURL())
  expect(afterBackground).not.toBe(beforeBackground)
  await page.getByRole('button', { name: 'Move V', exact: true }).click()
  const canvasBox = (await page.locator('.calibration-canvas-frame').boundingBox())!
  await page.mouse.move(canvasBox.x + canvasBox.width * .99, canvasBox.y + canvasBox.height * .55); await page.mouse.down()
  await page.mouse.move(canvasBox.x + canvasBox.width * .99 - 15, canvasBox.y + canvasBox.height * .55, { steps: 4 }); await page.mouse.up()
  await expect(page.getByLabel('Background X offset (%)', { exact: true })).not.toHaveValue('0')
  await page.screenshot({ path: 'work/background-transform-editor.png' })
  await page.getByLabel('Background horizontal position (%)', { exact: true }).focus(); await page.keyboard.press('Home'); for (let i = 0; i < 20; i++) await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: /Original border.*Vector rectangle/ }).click()
  await page.getByLabel('Border thickness (this layout, source px)', { exact: true }).fill('11')
  const borderX = page.getByLabel('Border X (%)', { exact: true }), borderWidth = page.getByLabel('Border width (%)', { exact: true })
  const beforeX = Number(await borderX.inputValue()), nw=(await page.getByRole('button',{name:'Scale from top left',exact:true}).boundingBox())!,se=(await page.getByRole('button',{name:'Scale from bottom right',exact:true}).boundingBox())!,selection={x:nw.x+nw.width/2,y:nw.y+nw.height/2,width:se.x-nw.x,height:se.y-nw.y}
  await page.getByRole('button', { name: 'Move V', exact: true }).click()
  await page.mouse.move(selection.x + selection.width * .95, selection.y + selection.height * .55); await page.mouse.down()
  await page.mouse.move(selection.x + selection.width * .95 - 10, selection.y + selection.height * .55 - 10, { steps: 5 }); await page.mouse.up()
  await expect.poll(async()=>Number(await borderX.inputValue())).toBeLessThan(beforeX)
  const initialWidth = Number(await borderWidth.inputValue()), handle = (await page.getByRole('button', { name: 'Scale from bottom right', exact: true }).boundingBox())!
  await page.mouse.move(handle.x + 7, handle.y + 7); await page.mouse.down(); await page.mouse.move(handle.x - 10, handle.y - 10, { steps: 5 }); await page.mouse.up()
  await expect.poll(async()=>Number(await borderWidth.inputValue())).toBeLessThan(initialWidth)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(Number(await borderWidth.inputValue())).toBeCloseTo(initialWidth, 1)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  const savedBorderWidth = await borderWidth.inputValue()
  await page.getByRole('button', { name: 'Back to layout previews', exact: false }).click()
  await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  await page.getByRole('button', { name: /Original border.*Vector rectangle/ }).click()
  await expect(page.getByLabel('Border thickness (this layout, source px)', { exact: true })).toHaveValue('11')
  await expect(borderWidth).toHaveValue(savedBorderWidth)
  await page.getByRole('button', { name: /^bg\b.*Background/ }).click()
  await expect(page.getByLabel('Background scale (%)', { exact: true })).toHaveValue('200')
  await expect(page.getByLabel('Background horizontal position (%)', { exact: true })).toHaveValue('20')
  await page.getByLabel('Background scale (%)', { exact: true }).fill('50')
  await expect(page.getByLabel('Background scale (%)', { exact: true })).toHaveValue('50')
  await page.getByLabel('Background X offset (%)', { exact: true }).fill('-60')
  await expect(page.getByLabel('Background X offset (%)', { exact: true })).toHaveValue('-60')
  expect(errors).toEqual([])
})
