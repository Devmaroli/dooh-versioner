import { expect, test } from '@playwright/test'
import fs from 'node:fs'

test('seven complete edits undo/redo with persistent history and default move/scale handles', async ({ page }) => {
  await page.goto('/'); await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'history_EN.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Zl1sAAAAASUVORK5CYII=', 'base64') })
  await page.getByRole('button', { name: /3 · Adapt/ }).click(); await page.getByRole('button', { name: 'Edit 2.6 Screen', exact: true }).click()
  const undo = page.getByRole('button', { name: 'Undo', exact: true }), redo = page.getByRole('button', { name: 'Redo', exact: true }), x = page.getByLabel('X position (%)', { exact: true })
  await expect(undo).toBeDisabled()
  const initial = await x.inputValue()
  for (let n = 1; n <= 7; n++) { await x.fill(String(n)); await page.getByRole('button', { name: 'Move V', exact: true }).click() }
  await page.getByText('History · 7 / 7 undo steps', { exact: true }).click()
  await expect(page.locator('.editor-history li')).toHaveCount(7)
  for (let n = 0; n < 7; n++) await undo.click()
  await expect(x).toHaveValue(initial); await expect(undo).toBeDisabled()
  for (let n = 0; n < 7; n++) await redo.click()
  await expect(x).toHaveValue('7'); await expect(redo).toBeDisabled()
  const handle = page.getByRole('button', { name: 'Scale from bottom right', exact: true })
  await expect(handle).toBeVisible()
  const beforeWidth = Number(await page.getByLabel('Width (%)', { exact: true }).inputValue()), b = (await handle.boundingBox())!
  await page.mouse.move(b.x + 7, b.y + 7); await page.mouse.down(); await page.mouse.move(b.x + 27, b.y + 27, { steps: 8 }); await page.mouse.up()
  await expect.poll(async()=>Number(await page.getByLabel('Width (%)', { exact: true }).inputValue())).toBeGreaterThan(beforeWidth)
  await undo.click()
  expect(Number(await page.getByLabel('Width (%)', { exact: true }).inputValue())).toBeCloseTo(beforeWidth, 1)
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.reload(); await page.getByRole('button', { name: /3 · Adapt/ }).click(); await page.getByRole('button', { name: 'Edit 2.6 Screen', exact: true }).click()
  await expect(redo).toBeEnabled()
})

test('linked untagged IKEA source can prepare border and independent words in one undoable action', async ({ page }) => {
  const fixture = process.env.IKEA_PSD
  test.skip(!fixture || !fs.existsSync(fixture), 'Set IKEA_PSD to the private local fixture.')
  await page.goto('/'); await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(fixture!)
  await page.getByLabel('Language for ikea.psd').selectOption('EN'); await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  await page.locator('.analyse-layer').nth(6).click(); await page.locator('.analyse-layer').nth(8).click({ modifiers: ['Control'] })
  await page.getByRole('button', { name: 'Link selected', exact: true }).click()
  await page.getByRole('button', { name: /3 · Adapt/ }).click(); await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  const selector = page.getByLabel('Main headline source', { exact: true })
  const candidate = await selector.locator('option').evaluateAll(options => options.map(o => ({ value: (o as HTMLOptionElement).value, text: o.textContent || '' })).find(o => /1522 × 732/.test(o.text)))
  expect(candidate).toBeDefined()
  await selector.selectOption({ index: 1 }); await page.getByRole('button', { name: 'Prepare border + words', exact: true }).click()
  await expect(page.locator('.preparation-result')).toContainText('No source changes applied')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await selector.selectOption(candidate!.value)
  await page.getByRole('button', { name: 'Prepare border + words', exact: true }).click()
  await expect(page.locator('.editor-layer-row').filter({ hasText: /Word [0-9]+ · embedded vector/ })).toHaveCount(5)
  await expect(page.getByRole('button', { name: /Original border.*Vector rectangle/ })).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.editor-layer-row').filter({ hasText: /Word [0-9]+ · embedded vector/ })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Original border.*Vector rectangle/ })).toHaveCount(0)
  await expect(page.locator('.editor-layer-row').filter({ hasText: 'Linked unassigned · 2 layers' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.locator('.editor-layer-row').filter({ hasText: /Word [0-9]+ · embedded vector/ })).toHaveCount(5)
  await page.screenshot({ path: 'work/history-prepared-headline.png' })
})
