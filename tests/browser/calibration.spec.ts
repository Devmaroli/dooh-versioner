import { expect, test } from '@playwright/test'
import fs from 'node:fs'
import { approveGuides, guideNames } from './helpers'

test('full background, multi-selection, links, visibility, edge anchoring and five focused guides persist', async ({ page }) => {
  test.setTimeout(90000)
  const fixture = process.env.IKEA_PSD
  test.skip(!fixture || !fs.existsSync(fixture), 'Set IKEA_PSD to the private local fixture.')
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(fixture!)
  await page.getByLabel('Language for ikea.psd').selectOption('EN')
  await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  const layers = page.locator('.analyse-layer')
  await layers.filter({ hasText: 'Newspaper 03' }).click()
  await page.getByRole('button', { name: 'Selected layer', exact: true }).click()
  await expect(page.getByLabel('View bounds', { exact: true })).toHaveValue('layer')
  await expect(page.locator('.analyse-toolbar')).toContainText('2964 × 1653 px · Origin -521, -286')
  await page.getByRole('button', { name: 'Draw background area', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'X', exact: true }).fill('-400')
  await page.getByRole('spinbutton', { name: 'Y', exact: true }).fill('-200')
  await page.getByRole('spinbutton', { name: 'Width', exact: true }).fill('80')
  await page.getByRole('spinbutton', { name: 'Height', exact: true }).fill('80')
  await page.getByRole('button', { name: 'Use this background area', exact: true }).click()
  await expect(page.locator('.background-status')).toContainText('Background area saved')
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.reload(); await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  await expect(page.locator('.background-status')).toContainText('at -400, -200')
  await layers.filter({ hasText: 'Newspaper 03' }).click()
  await page.getByRole('button', { name: 'Draw background area', exact: true }).click()
  for (const [label, value] of [['X', '900'], ['Y', '50'], ['Width', '500'], ['Height', '200']]) await page.getByRole('spinbutton', { name: label, exact: true }).fill(value)
  await page.getByRole('button', { name: 'Use this background area', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'work/analyse-full-background.png', fullPage: true })
  await layers.nth(4).click()
  await page.getByRole('button', { name: 'Campaign stamp / label', exact: true }).click()
  await expect(page.getByLabel('Edge', { exact: true })).toHaveValue('top')
  await layers.nth(6).click()
  await page.getByRole('button', { name: 'Main headline', exact: true }).click()
  await page.getByRole('button', { name: 'Trace original border', exact: true }).click()
  for (const [label, value] of [['X', '99'], ['Y', '279'], ['Width', '1522'], ['Height', '732']]) await page.getByRole('spinbutton', { name: label, exact: true }).fill(value)
  await page.getByRole('button', { name: 'Use original border', exact: true }).click()
  await expect(page.locator('.background-status')).toContainText('Original border rebuilt')
  await page.getByLabel('Border thickness (source px)', { exact: true }).fill('8')
  await layers.nth(0).click({ modifiers: ['Control'] })
  await expect(page.locator('.analyse-layer.selected')).toHaveCount(2)
  await page.getByRole('button', { name: 'Main headline', exact: true }).click()
  await page.getByRole('button', { name: 'Link selected', exact: true }).click()
  await expect(layers.filter({ hasText: 'Linked' })).toHaveCount(2)
  await page.getByLabel('Keep to edge', { exact: true }).check()
  await page.getByLabel('Edge', { exact: true }).selectOption('right')
  await page.getByLabel('Edge margin (% of short side)', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Hide selected', exact: true }).click()
  expect(await page.locator('.analyse-artboard canvas').evaluate((c: HTMLCanvasElement) => {
    const d = c.getContext('2d')!.getImageData(0, 0, c.width, c.height).data
    for (let i = 3; i < d.length; i += 4) if (d[i] > 0) return false
    return true
  })).toBe(true)
  await page.getByRole('button', { name: 'Show selected', exact: true }).click()
  await page.getByLabel('Alpha checkerboard', { exact: true }).uncheck()
  await page.getByLabel('Preview background color', { exact: true }).evaluate((el: HTMLInputElement) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(el, '#eaedf2')
    el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(page.locator('.analyse-artboard')).toHaveCSS('background-color', 'rgb(234, 237, 242)')
  await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button',{name:/1 · Import/}).click()
  await page.getByText(/Choose target screens ·/).click()
  await page.locator('.screens label').filter({hasText:'The Gate Mall Outdoor 948×648'}).getByRole('checkbox').check()
  await page.getByRole('button',{name:/3 · Adapt/}).click()
  await expect(page.locator('.calibration-card')).toHaveCount(5)
  for (const name of guideNames) await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.getByText('Topaz (Sync)', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Use these guides for full adaptation', exact: true })).toBeDisabled()
  await page.screenshot({ path: 'work/calibration-five-previews.png', fullPage: true })
  await page.locator('.calibration-thumbnail').first().dblclick()
  const dialog = page.getByRole('dialog', { name: 'Edit 2.6 Screen', exact: true })
  await expect(dialog).toBeVisible()
  const box = (await dialog.boundingBox())!; expect(box.x).toBe(0); expect(box.y).toBe(0); expect(box.width).toBe(1440)
  const beforeX = Number(await page.getByLabel('X position (%)', { exact: true }).inputValue())
  await page.getByLabel('Width (%)', { exact: true }).fill('20')
  const x = Number(await page.getByLabel('X position (%)', { exact: true }).inputValue())
  expect(x).toBeCloseTo(beforeX, 1)
  const oldY = Number(await page.getByLabel('Y position (%)', { exact: true }).inputValue())
  await page.getByLabel('Y position (%)', { exact: true }).fill(String(oldY + 1))
  expect(Number(await page.getByLabel('Y position (%)', { exact: true }).inputValue())).toBeGreaterThan(oldY)
  await page.screenshot({ path: 'work/calibration-focused-editor.png' })
  await page.getByRole('button', { name: 'Back to layout previews', exact: false }).click()
  await expect(dialog).not.toBeVisible()
  await approveGuides(page)
  await expect(page.locator('.pair')).toHaveCount(7)
  await expect(page.getByRole('button', { name: 'Export review ZIP', exact: true })).toBeEnabled()
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.reload(); await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await expect(page.getByText('5 / 5 guides approved', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit 2.6 Screen', exact: true }).click()
  await expect(page.getByLabel('Width (%)', { exact: true })).toHaveValue('20')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: /2 · Analyse/ }).click()
  await expect(page.getByLabel('Preview background color', { exact: true })).toHaveValue('#eaedf2')
  await expect(layers.filter({ hasText: 'Linked' })).toHaveCount(2)
  await page.getByRole('button', { name: 'Hide layer 1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Export review ZIP', exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})
