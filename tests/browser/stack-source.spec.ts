import { expect, test } from '@playwright/test'
import fs from 'node:fs'

test('editor detects the IKEA source border, splits five words and renders the reordered layer stack', async ({ page }) => {
  const fixture = process.env.IKEA_PSD
  test.skip(!fixture || !fs.existsSync(fixture), 'Set IKEA_PSD to the private local fixture.')
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/'); await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(fixture!)
  await page.getByLabel('Language for ikea.psd').selectOption('EN')
  await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  await page.locator('.analyse-layer').nth(6).click()
  await page.getByRole('button', { name: 'Main headline', exact: true }).click()
  await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  await page.locator('.editor-layer-row').filter({ hasText: /headline ·/ }).getByRole('button', { name: /^Select layer / }).click()
  await page.getByRole('button', { name: 'Detect original border', exact: true }).click()
  await expect(page.locator('.source-tool-status')).toContainText('Original border detected')
  await expect(page.getByRole('button', { name: /Original border.*Vector rectangle/ })).toBeVisible()
  await page.getByRole('button', { name: 'Split headline into words', exact: true }).click()
  await expect(page.locator('.source-tool-status')).toContainText('Separated 5')
  await expect(page.locator('.editor-layer-row').filter({ hasText: /Word [0-9]+ · embedded vector/ })).toHaveCount(5)
  await page.screenshot({ path: 'work/editor-border-and-five-words.png' })
  const before = await page.locator('.calibration-canvas-frame .proof-canvas canvas').evaluate((c: HTMLCanvasElement) => c.toDataURL())
  await page.getByRole('button', { name: /bg.*Background.*original/ }).click()
  const up = page.getByRole('button', { name: 'Move layer up', exact: true })
  for (let i = 0; i < 30 && await up.isEnabled(); i++) await up.click()
  await expect(up).toBeDisabled()
  await expect(page.locator('.editor-layer-row:not([aria-expanded])').first()).toContainText('bg')
  const after = await page.locator('.calibration-canvas-frame .proof-canvas canvas').evaluate((c: HTMLCanvasElement) => c.toDataURL())
  expect(after).not.toBe(before)
  const word = page.locator('.editor-layer-row').filter({ hasText: 'Word 1 · embedded vector' })
  await word.getByRole('button', { name: /^Select layer / }).click()
  const canvas = (await page.locator('.calibration-canvas-frame').boundingBox())!
  await page.mouse.click(canvas.x + canvas.width / 2, canvas.y + canvas.height / 2)
  await expect(page.getByLabel('Element', { exact: true })).toHaveValue('background')
  await page.screenshot({ path: 'work/stack-order-background-front.png' })
  const bgRow = page.locator('.editor-layer-row:not([aria-expanded])').first(), target = page.locator('.editor-layer-row:not([aria-expanded])').nth(2)
  await bgRow.dragTo(target)
  await expect(page.locator('.editor-layer-row:not([aria-expanded])').first()).not.toContainText('bg')
  await page.getByRole('button', { name: 'Back to layout previews', exact: false }).click()
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.reload(); await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  await expect(page.locator('.editor-layer-row').filter({ hasText: /Word [0-9]+ · embedded vector/ })).toHaveCount(5)
  await expect(page.locator('.editor-layer-row:not([aria-expanded])').first()).not.toContainText('bg')
  expect(errors).toEqual([])
})
