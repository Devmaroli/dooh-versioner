import { expect, test } from '@playwright/test'
import { writePsdBuffer } from 'ag-psd'

function pixels(rgb: number[]) {
  const data = new Uint8ClampedArray(32 * 32 * 4)
  for (let i = 0; i < data.length; i += 4) data.set([...rgb, 255], i)
  return { width: 32, height: 32, data }
}

test('analyse shows roles, artwork and a persistent layer tree side by side', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const composite = new Uint8ClampedArray(64 * 64 * 4)
  for (let y = 0; y < 32; y++) for (let x = 0; x < 64; x++) composite.set(x < 32 ? [180,40,40,255] : [40,80,180,255], (y * 64 + x) * 4)
  const buffer = writePsdBuffer({ width: 64, height: 64, imageData: { width: 64, height: 64, data: composite }, children: [{ name: 'Campaign folder', children: [{ name: 'Leaf red', left: 0, top: 0, imageData: pixels([180, 40, 40]) }, { name: 'Leaf blue', left: 32, top: 0, imageData: pixels([40, 80, 180]) }] }] }, { generateThumbnail: false })
  await page.goto('/')
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'grouped_EN.psd', mimeType: 'application/octet-stream', buffer })
  await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  const roles = page.getByRole('complementary', { name: 'Tagging panel' })
  const art = page.getByRole('group', { name: 'Artwork background selection' })
  const layers = page.getByRole('complementary', { name: 'Layers panel' })
  await expect(roles.getByRole('heading', { name: 'What is this layer?' })).toBeVisible()
  await expect(layers.getByRole('treeitem', { name: /Campaign folder/ })).toHaveAttribute('aria-expanded', 'true')
  const boxes = await Promise.all([roles, art, layers].map(locator => locator.boundingBox()))
  expect(boxes[1]!.x).toBeLessThan(boxes[0]!.x)
  expect(boxes[1]!.x + boxes[1]!.width).toBeLessThanOrEqual(boxes[0]!.x + 2)
  expect(boxes[0]!.x + boxes[0]!.width).toBeLessThanOrEqual(boxes[2]!.x + 2)
  expect(boxes[0]!.y).toBeLessThan(900)
  expect(boxes[2]!.y).toBeLessThan(900)
  await page.getByRole('separator', { name: 'Resize tagging panel' }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(async () => (await roles.boundingBox())!.width).toBeCloseTo(310, 0)
  await page.getByRole('button', { name: 'Collapse tagging panel', exact: true }).click()
  await expect.poll(async () => (await roles.boundingBox())!.width).toBeCloseTo(40, 0)
  await page.getByRole('button', { name: 'Expand tagging panel', exact: true }).click()
  const resize = await page.getByRole('separator', { name: 'Resize layers panel' }).boundingBox()
  await page.mouse.move(resize!.x + 3, resize!.y + 20); await page.mouse.down()
  await page.mouse.move(resize!.x - 17, resize!.y + 20); await page.mouse.up()
  await expect.poll(async () => (await layers.boundingBox())!.width).toBeCloseTo(320, 0)
  await page.getByRole('button', { name: 'Collapse layers panel', exact: true }).click()
  await expect.poll(async () => (await layers.boundingBox())!.width).toBeCloseTo(40, 0)
  await page.getByRole('button', { name: 'Expand layers panel', exact: true }).click()
  await page.getByRole('button', { name: 'Leaf red', exact: true }).click()
  await expect(roles.locator('.tagger-visual strong')).toHaveText('Leaf red')
  await roles.getByRole('button', { name: 'Center', exact: true }).click()
  await expect(roles.getByRole('button', { name: 'Center', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await roles.getByRole('button', { name: 'Can crop', exact: true }).click()
  await expect(roles.getByRole('button', { name: 'Can crop', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await art.click({ position: { x: (await art.boundingBox())!.width * .75, y: 12 } })
  await expect(roles.locator('.tagger-visual strong')).toHaveText('Leaf blue')
  await roles.locator('.analyse-panel-content').evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: 'work/analyse-three-columns.png' })
  await layers.getByRole('button', { name: 'Collapse Campaign folder', exact: true }).click()
  await expect(layers.getByRole('treeitem', { name: /Campaign folder/ })).toHaveAttribute('aria-expanded', 'false')
  await expect(layers.getByRole('treeitem', { name: /Leaf red/ })).toHaveCount(0)
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.waitForTimeout(400)
  await page.reload()
  await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  await expect(page.getByRole('treeitem', { name: /Campaign folder/ })).toHaveAttribute('aria-expanded', 'false')
  await page.setViewportSize({ width: 1280, height: 800 })
  const again = await Promise.all([roles, art, layers].map(locator => locator.boundingBox()))
  expect(again[1]!.x).toBeLessThan(again[0]!.x)
  expect(again[2]!.x).toBeGreaterThan(again[0]!.x)
  expect(again[0]!.width).toBeCloseTo(310, 0)
  expect(again[2]!.width).toBeCloseTo(320, 0)
})
