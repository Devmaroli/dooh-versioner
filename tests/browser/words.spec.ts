import { expect, test } from '@playwright/test'
import fs from 'node:fs'

test('IKEA headline becomes separate source-pixel words; editor groups, aligns and distributes them', async ({ page }) => {
  const fixture = process.env.IKEA_PSD
  test.skip(!fixture || !fs.existsSync(fixture), 'Set IKEA_PSD to the private local fixture.')
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/'); await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(fixture!)
  await page.getByLabel('Language for ikea.psd').selectOption('EN')
  await page.getByRole('button', { name: 'Continue to Analyse' }).click()
  await page.locator('.analyse-layer').nth(6).click()
  await page.getByRole('button', { name: 'Main headline', exact: true }).click()
  await page.getByRole('button', { name: 'Trace original border', exact: true }).click()
  for (const [label, value] of [['X', '99'], ['Y', '279'], ['Width', '1522'], ['Height', '732']]) await page.getByRole('spinbutton', { name: label, exact: true }).fill(value)
  await page.getByRole('button', { name: 'Use original border', exact: true }).click()
  await page.getByLabel('View bounds', { exact: true }).selectOption('artboard')
  await page.locator('.analyse-artboard canvas').evaluate((c: HTMLCanvasElement) => { (window as any).__wordBefore = c.getContext('2d')!.getImageData(0, 0, c.width, c.height).data })
  await page.getByRole('button', { name: 'Separate words (source pixels)', exact: true }).click()
  await expect(page.locator('.background-status')).toContainText('Separated 5 source-pixel pieces')
  await expect(page.locator('.analyse-layer').filter({ hasText: /Word [0-9]+ · source pixels/ })).toHaveCount(5)
  const pixels = await page.locator('.analyse-artboard canvas').evaluate((c: HTMLCanvasElement) => {
    const before = (window as any).__wordBefore, after = c.getContext('2d')!.getImageData(0, 0, c.width, c.height).data
    let missingOpaque = 0, alphaBefore = 0, alphaAfter = 0
    for (let i = 3; i < after.length; i += 4) { if (before[i] > 240 && after[i] < 200) missingOpaque++; alphaBefore += before[i]; alphaAfter += after[i] }
    return { missingOpaque, alphaBefore, alphaAfter }
  })
  expect(pixels.missingOpaque).toBe(0)
  expect(Math.abs(pixels.alphaAfter / pixels.alphaBefore - 1)).toBeLessThan(.005)
  await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  const element = page.getByLabel('Element', { exact: true })
  await element.selectOption({ label: 'Word 1 · source pixels' })
  await page.getByLabel('Select element Word 2 · source pixels', { exact: true }).check()
  await page.getByRole('button', { name: 'Link selected layers', exact: true }).click()
  await expect(page.locator('.editor-layer-row.selected')).toHaveCount(2)
  await expect(page.getByRole('toolbar', { name: 'Layer actions' }).getByRole('button', { name: 'Unlink selected layers', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Unlink selected layers', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByLabel('Width (%)', { exact: true }).fill('40')
  await page.getByRole('button', { name: 'Unlink selected layers', exact: true }).click()
  await expect(page.locator('.guide-object.selected')).toHaveCount(2)
  await page.getByRole('button', { name: 'Link selected layers', exact: true }).click()
  await expect(page.locator('.editor-layer-row.selected')).toHaveCount(2)
  await page.getByRole('button', { name: 'Unlink selected layers', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Group selected elements', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Group selected elements', exact: true }).click()
  await expect(element.locator('option:checked')).toHaveText('Group · 2 elements')
  await page.getByLabel('Width (%)', { exact: true }).fill('60')
  await page.getByRole('button', { name: 'Ungroup selected elements', exact: true }).click()
  await expect(page.locator('.guide-object.selected')).toHaveCount(2)
  await page.getByRole('button', { name: 'Left', exact: true }).click()
  await element.selectOption({ label: 'Word 1 · source pixels' })
  const x1 = await page.getByLabel('X position (%)', { exact: true }).inputValue()
  await element.selectOption({ label: 'Word 2 · source pixels' })
  expect(await page.getByLabel('X position (%)', { exact: true }).inputValue()).toBe(x1)
  await page.getByLabel('Select element Word 1 · source pixels', { exact: true }).check()
  await page.getByLabel('Select element Word 3 · source pixels', { exact: true }).check()
  await expect(page.getByRole('button', { name: 'Distribute vertically', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Distribute vertically', exact: true }).click()
  await element.selectOption({ label: 'Word 4 · source pixels' })
  await page.getByLabel('Alignment reference', { exact: true }).selectOption('canvas')
  await page.getByRole('button', { name: 'Horizontal center', exact: true }).click()
  const x = Number(await page.getByLabel('X position (%)', { exact: true }).inputValue()), w = Number(await page.getByLabel('Width (%)', { exact: true }).inputValue())
  expect(x + w / 2).toBeCloseTo(50, 1)
  await page.screenshot({ path: 'work/source-word-editor.png' })
  await page.getByRole('button', { name: 'Back to five previews', exact: false }).click()
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.reload(); await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit Alshaheed - Mupi', exact: true }).click()
  await expect(element.locator('option').filter({ hasText: /Word [0-9]+ · source pixels/ })).toHaveCount(5)
  await page.keyboard.press('Escape'); await page.getByRole('button', { name: /2 · Analyse/ }).click()
  await page.locator('.analyse-layer').filter({ hasText: 'Word 1 · source pixels' }).click()
  await page.getByRole('button', { name: 'Restore combined words', exact: true }).click()
  await expect(page.locator('.analyse-layer').filter({ hasText: /Word [0-9]+ · source pixels/ })).toHaveCount(0)
  await page.locator('.analyse-layer').nth(8).click()
  await page.getByRole('button', { name: 'Brand logo', exact: true }).click()
  await expect(page.getByLabel('Contains a logo — preserve as one', { exact: true })).toBeChecked()
  await expect(page.getByRole('button', { name: 'Separate words (source pixels)', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Trace original border', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Main headline', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Separate words (source pixels)', exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})
