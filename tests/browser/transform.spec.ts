import { expect, test } from '@playwright/test'

test('scale handles and numerical width keep the selected anchor fixed and retain edits', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'transform_EN.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Zl1sAAAAASUVORK5CYII=', 'base64') })
  await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit 2.6 Screen', exact: true }).click()
  const x = page.getByLabel('X position (%)', { exact: true }), y = page.getByLabel('Y position (%)', { exact: true }), width = page.getByLabel('Width (%)', { exact: true })
  await width.fill('20'); await x.fill('35'); await y.fill('25')
  await page.getByRole('button', { name: 'Anchor centre', exact: true }).click()
  await width.fill('30')
  expect(Number(await x.inputValue())).toBeCloseTo(30, 1)
  expect(Number(await y.inputValue())).toBeCloseTo(11.67, 1)
  await page.getByRole('button', { name: 'Scale S', exact: true }).click()
  const handle = page.getByRole('button', { name: 'Scale from bottom right', exact: true })
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 20, box.y + box.height / 2 + 20, { steps: 5 }); await page.mouse.up()
  const newWidth = Number(await width.inputValue()), newX = Number(await x.inputValue())
  expect(newWidth).toBeGreaterThan(30)
  expect(newX + newWidth / 2).toBeCloseTo(45, 1)
  await page.screenshot({ path: 'work/scale-anchor-editor.png' })
  await page.getByRole('button', { name: 'Move V', exact: true }).click()
  await expect(handle).toBeVisible()
  await page.keyboard.press('s'); await expect(handle).toBeVisible()
  await page.getByRole('button', { name: 'Back to five previews', exact: false }).click()
  await expect(page.getByText('Saved on this device')).toBeVisible()
  await page.reload(); await page.getByRole('button', { name: /3 · Adapt/ }).click()
  await page.getByRole('button', { name: 'Edit 2.6 Screen', exact: true }).click()
  expect(Number(await width.inputValue())).toBeCloseTo(newWidth, 1)
  expect(Number(await x.inputValue())).toBeCloseTo(newX, 1)
  await page.getByRole('button', { name: 'Move V', exact: true }).click()
  const object = page.locator('.guide-object.selected'), objectBox = (await object.boundingBox())!
  await page.mouse.move(objectBox.x + objectBox.width / 2, objectBox.y + objectBox.height / 2); await page.mouse.down()
  await page.mouse.move(objectBox.x + objectBox.width / 2 + 15, objectBox.y + objectBox.height / 2, { steps: 4 }); await page.mouse.up()
  expect(Number(await x.inputValue())).toBeGreaterThan(newX)
  const beforeNudge = Number(await x.inputValue())
  await page.keyboard.press('Shift+ArrowRight')
  expect(Number(await x.inputValue())).toBeCloseTo(beforeNudge + 10 / 1536 * 100, 1)
  await x.fill('-20'); await expect(x).toHaveValue('-20')
  await width.fill('150'); await expect(width).toHaveValue('150')
  expect(errors).toEqual([])
})
